"""memory_bridge: distill graded battery rows into per-model memory cards.

Ladder phase 4 (SIS lane): the weekly routing review used to propose from
receipts alone; combining receipts with battery memory was done by hand
(2026-10-25 proposal). This bridge automates the memory plane:

  eval_results.jsonl (graded rows) -> fleet/memory/routing-memory.{json,md}

A card per model: n rows, pass rate, strong/weak tasks, cost per pass,
recent fail history. The weekly review (weekly_routing_review.py) loads
these cards so every proposal cites both evidence planes, not folklore.

Usage:
  python fleet/memory_bridge.py            # regenerate cards
  python fleet/memory_bridge.py --check    # self-grade: fresh + covering + consistent
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

FLEET = Path(__file__).resolve().parent
RESULTS = FLEET / "evals" / "eval_results.jsonl"
MEMORY = FLEET / "memory"
CARD_JSON = MEMORY / "routing-memory.json"
CARD_MD = MEMORY / "routing-memory.md"

RECENT_FAILS = 5          # fail rows kept per model
STRONG_RATE = 0.95        # task pass rate >= this = strong


def load_rows() -> list[dict]:
    if not RESULTS.exists():
        return []
    return [json.loads(l) for l in
            RESULTS.read_text(encoding="utf-8").splitlines() if l.strip()]


def build_cards(rows: list[dict]) -> dict:
    """Group graded rows into per-model memory cards."""
    as_of = datetime.now(timezone.utc).isoformat(timespec="seconds")
    by_model: dict[str, list] = defaultdict(list)
    for r in rows:
        if r.get("harness") != "gateway" or not r.get("task"):
            continue
        by_model[r["model"]].append(r)
    cards = {}
    for model, rs in sorted(by_model.items()):
        n = len(rs)
        passed = sum(1 for r in rs if r.get("ok"))
        fails = [r for r in rs if not r.get("ok")]
        per_task = defaultdict(list)
        for r in rs:
            per_task[r["task"]].append(bool(r.get("ok")))
        strong = sorted(t for t, oks in per_task.items()
                        if oks and sum(oks) / len(oks) >= STRONG_RATE)
        weak = sorted(set(r["task"] for r in fails
                          if r["task"] not in strong))
        spend_rows = [r.get("cost_usd") for r in rs]
        priced = [c for c in spend_rows if c is not None]
        unpriced = len(spend_rows) - len(priced)
        spend = sum(priced)
        # cost honesty: unpriced rows are UNKNOWN, not free - totals and
        # per-pass figures are null rather than silently understated
        if unpriced:
            cost_total = None
            cost_per_pass = None
        else:
            cost_total = round(spend, 6)
            cost_per_pass = round(spend / passed, 6) if passed else None
        cards[model] = {
            "model": model,
            "as_of": as_of,
            "source": "fleet/evals/eval_results.jsonl",
            "n_rows": n,
            "pass_rate": round(passed / n, 4) if n else None,
            "strong_tasks": strong,
            "weak_tasks": weak,
            "cost_total_usd": cost_total,
            "cost_per_pass_usd": cost_per_pass,
            "cost_priced_rows": len(priced),
            "cost_unpriced_rows": unpriced,
            "recent_fails": [
                {"task": r["task"], "ts": r["ts"]}
                for r in fails[-RECENT_FAILS:]
            ],
            "first_row_ts": rs[0]["ts"],
            "last_row_ts": rs[-1]["ts"],
        }
    return {"as_of": as_of, "source": str(RESULTS), "cards": cards}


def render_md(doc: dict) -> str:
    lines = [
        "# Routing memory (generated)",
        "",
        f"- as_of: {doc['as_of']}",
        f"- source: {doc['source']} (graded battery rows only)",
        "- regenerated by `python fleet/memory_bridge.py`; `--check` gates it",
        "",
        "| model | n | pass | $/pass | strong | weak |",
        "|---|---|---|---|---|---|",
    ]
    for m, c in doc["cards"].items():
        rate = f"{c['pass_rate'] * 100:.1f}%" if c["pass_rate"] is not None else "-"
        if c.get("cost_per_pass_usd") is None:
            cpp = f"unknown({c.get('cost_unpriced_rows', '?')} unpriced)"
        else:
            cpp = f"${c['cost_per_pass_usd']:.6f}"
        lines.append(f"| `{m}` | {c['n_rows']} | {rate} | {cpp} "
                     f"| {', '.join(c['strong_tasks'][:8]) or '-'} "
                     f"| {', '.join(c['weak_tasks']) or '-'} |")
    lines += ["", "Recent fails per model:", ""]
    for m, c in doc["cards"].items():
        for f in c["recent_fails"]:
            lines.append(f"- `{m}` {f['task']} ({f['ts'][:19]})")
    if not any(c["recent_fails"] for c in doc["cards"].values()):
        lines.append("- (none)")
    return "\n".join(lines) + "\n"


def write_cards(doc: dict) -> None:
    MEMORY.mkdir(exist_ok=True)
    CARD_JSON.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
    CARD_MD.write_text(render_md(doc), encoding="utf-8")


def check() -> int:
    """Self-grade: committed cards must be fresh, covering, consistent."""
    problems = []
    rows = load_rows()
    fresh = build_cards(rows)
    if not CARD_JSON.exists():
        print("FAIL: routing-memory.json missing (run without --check first)")
        return 1
    committed = json.loads(CARD_JSON.read_text(encoding="utf-8"))
    ledger_models = {r["model"] for r in rows if r.get("harness") == "gateway"}
    card_models = set(committed.get("cards", {}))
    missing = ledger_models - card_models
    if missing:
        problems.append(f"models with rows but no card: {sorted(missing)}")
    for m in card_models & set(fresh["cards"]):
        c, f = committed["cards"][m], fresh["cards"][m]
        for key in ("n_rows", "pass_rate", "weak_tasks", "strong_tasks"):
            if c.get(key) != f.get(key):
                problems.append(f"{m}.{key} committed={c.get(key)} live={f.get(key)}")
    if problems:
        print("FAIL:")
        for p in problems:
            print(" -", p)
        return 1
    print(f"memory cards OK: {len(card_models)} models, "
          f"{len(rows)} graded rows, fresh + covering + consistent")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.check:
        return check()
    rows = load_rows()
    doc = build_cards(rows)
    write_cards(doc)
    print(f"memory cards written: {len(doc['cards'])} models from {len(rows)} rows")
    for m, c in doc["cards"].items():
        rate = f"{c['pass_rate'] * 100:.1f}%" if c["pass_rate"] is not None else "-"
        print(f"  {m}: n={c['n_rows']} pass={rate} weak={c['weak_tasks'] or '-'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())